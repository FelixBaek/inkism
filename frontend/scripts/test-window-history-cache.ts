import assert from 'node:assert/strict';
import {importTestModule} from './import-test-module.ts';
const {windowHistory,retainWindowHistory,advanceWindowHistory,forgetWindowHistory,nextHistorySession} = await importTestModule(new URL('../src/lib/window-history-cache.ts',import.meta.url));
const record=(h,before='a',after='ab')=>h.record({from:0,offset:0,before,after,beforeCount:1,afterCount:1,session:nextHistorySession(),group:1,time:1});
const h=windowHistory('note',1,'utf8');record(h);retainWindowHistory('note',1,'utf8',h);
advanceWindowHistory('note',1,2);assert.equal(windowHistory('note',2,'utf8'),h);
h.apply('undo','ab');assert.equal(windowHistory('note',2,'utf8').canRedo,true);
assert.equal(windowHistory('note',3,'utf8').canRedo,false);
const changedEncoding=windowHistory('note',3,'utf8');record(changedEncoding);
assert.equal(windowHistory('note',3,'utf16').canUndo,false);
const forgotten=windowHistory('note',3,'utf8');record(forgotten);forgetWindowHistory('note');
assert.equal(windowHistory('note',3,'utf8').canUndo,false);
const first=windowHistory('first',1,'utf8');record(first);
for(let i=0;i<16;i++)windowHistory('bounded-'+i,1,'utf8');
assert.equal(windowHistory('first',1,'utf8').canUndo,false);
assert.equal(first.canUndo,true,'eviction must not mutate attached editor history');
const large='x'.repeat(9*1024*1024);
const a=windowHistory('large-a',1,'utf8');record(a,large,'changed');retainWindowHistory('large-a',1,'utf8',a);
const b=windowHistory('large-b',1,'utf8');record(b,large,'changed');retainWindowHistory('large-b',1,'utf8',b);
assert.equal(windowHistory('large-a',1,'utf8').canUndo,false,'aggregate byte cap evicts old histories');
assert.equal(a.canUndo,true);
assert.equal(windowHistory('large-b',1,'utf8'),b);
console.log('PASS: session history revision/encoding guards, redo, explicit invalidation, 16-note/32MiB caps preserve attached history');
