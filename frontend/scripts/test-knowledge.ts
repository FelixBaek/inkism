import assert from 'node:assert/strict';
import {build} from 'esbuild';
import type {GraphData} from '../src/lib/knowledge';
const bundled=await build({stdin:{contents:"export * from './lib/knowledge';",resolveDir:new URL('../src/',import.meta.url).pathname,loader:'ts'},bundle:true,write:false,format:'cjs',platform:'node',logLevel:'error'});
const module={exports:{}};
new Function('module','exports',bundled.outputFiles[0].text)(module,module.exports);
const {graphNeighborhood,graphLayout,parseReference}=module.exports as typeof import('../src/lib/knowledge');
const graph:GraphData={nodes:['a','b','c','d'].map(id=>({id,title:id,tags:[],aliases:[]})),edges:[{source:'a',target:'b'},{source:'b',target:'c'},{source:'c',target:'a'}],truncated:false};
assert.deepEqual([...graphNeighborhood(graph,'a',1)].sort(),['a','b','c']);
assert.deepEqual([...graphNeighborhood(graph,'d',3)],['d']);
const positions=graphLayout(graph.nodes,graph.edges);assert.deepEqual(positions,graphLayout(graph.nodes,graph.edges));
assert.ok(positions.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.y)&&p.x>=40&&p.x<=760&&p.y>=35&&p.y<=525));
assert.deepEqual(graphLayout([],[]),[]);
assert.deepEqual(parseReference('note://daily-2026-10-12#%5Eparagraph|Read it',true),{target:'daily-2026-10-12',anchor:'%5Eparagraph',label:'Read it',embed:true});
assert.deepEqual(parseReference('#Heading'),{target:'',anchor:'Heading',label:'#Heading',embed:false});
console.log('PASS knowledge: cyclic/orphan graph and anchor references');
