import assert from 'node:assert/strict';
import {calculate,aggregate} from '../src/lib/collection-calculation.ts';
import type {KnowledgeItem,SavedView} from '../src/lib/knowledge';
const note={id:'a',properties:[{name:'점수',type:'number',value:4}]} as KnowledgeItem;
assert.deepEqual(calculate('[점수] * (2 + 3) / 2',note),{value:10});
assert.deepEqual(calculate('1/0',note),{error:'zero'});
assert.deepEqual(calculate('[missing]+1',note),{error:'missing'});
assert.deepEqual(calculate('globalThis.process.exit()',note),{error:'syntax'});
assert.deepEqual(calculate('2**3',note),{error:'syntax'});
assert.deepEqual(calculate('('.repeat(40)+'1'+')'.repeat(40),note),{error:'limit'});
assert.deepEqual(calculate('1e9',note),{error:'syntax'});
const view={aggregate:{operation:'sum',property:'점수'}} as SavedView;
assert.deepEqual(aggregate([note,{id:'b',properties:[]} as KnowledgeItem],view),{value:4,errors:0});
assert.deepEqual(aggregate([note],{...view,formulas:[{id:'f',name:'bad',expression:'1/0'}],aggregate:{operation:'sum',property:'formula:f'}}),{value:null,errors:1});
console.log('PASS bounded arithmetic and aggregate missing/error behavior');
const rich={...note,properties:[...note.properties,{name:'name',type:'text',value:'한😀'},{name:'due',type:'date',value:'2024-02-29'},{name:'links',type:'relation',value:['b','b']}]} as KnowledgeItem;
assert.deepEqual(calculate('concat(upper("abc"), [name])',rich),{value:'ABC한😀'});
assert.deepEqual(calculate('length([name])',rich),{value:2});
assert.deepEqual(calculate('if([점수] > 3, "yes", [missing])',rich),{value:'yes'});
assert.deepEqual(calculate('if(false, 1 / 0, 7)',rich),{value:7});
assert.deepEqual(calculate('days_between([due], "2024-03-01")',rich),{value:1});
assert.deepEqual(calculate('year("2023-02-29")',rich),{error:'syntax'});
assert.deepEqual(calculate('relation_sum([links], "score")',rich,[{id:'b',properties:[{name:'score',type:'number',value:5}]} as KnowledgeItem]),{value:5});
assert.deepEqual(calculate('relation_sum([links], "score")',rich),{error:'missing'});
assert.deepEqual(calculate('"1" + 2',rich),{error:'missing'});
assert.deepEqual(calculate('constructor("return process")()',rich),{error:'syntax'});
assert.deepEqual(calculate('if(1, 2, 3)',rich),{error:'missing'});
assert.deepEqual(aggregate([rich],{...view,formulas:[{id:'s',name:'string',expression:'"text"'}],aggregate:{operation:'sum',property:'formula:s'}}),{value:null,errors:0});
console.log('PASS typed strings, Unicode length, lazy conditions, UTC dates, relation deduplication/missing links and code rejection');
