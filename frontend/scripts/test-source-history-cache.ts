import assert from 'node:assert/strict';
import {EditorState} from '@codemirror/state';
import {history,historyField,undo,redo} from '@codemirror/commands';
import {importTestModule} from './import-test-module.ts';
const {acquireSourceHistory,releaseSourceHistory,advanceSourceHistory,forgetSourceHistory} = await importTestModule(new URL('../src/lib/source-history-cache.ts',import.meta.url));
const state=(doc,value?)=>EditorState.create({doc,extensions:[history(),...(value?[historyField.init(()=>value)]:[])]});
const command=(cmd,current)=>{let next=current;assert.equal(cmd({state:current,dispatch:tr=>next=tr.state}),true);return next;};
const baseline='가'.repeat(20*1024*1024);
const first=acquireSourceHistory('large',1);let s=state(baseline);
s=s.update({changes:{from:baseline.length,insert:'😀'}}).state;
advanceSourceHistory('large',1,2);releaseSourceHistory('large',first.handle,s);
const second=acquireSourceHistory('large',2);
assert.ok(second.value,'unchanged 40MiB body must not count toward 32MiB history cap');
s=command(undo,state(s.doc,second.value));assert.equal(s.doc.toString(),baseline);
releaseSourceHistory('large',second.handle,s);
const third=acquireSourceHistory('large',2);s=command(redo,state(s.doc,third.value));assert.ok(s.doc.toString().endsWith('😀'));
forgetSourceHistory('large');releaseSourceHistory('large',third.handle,s);
assert.equal(acquireSourceHistory('large',2).value,undefined,'late cleanup must not revive invalidated history');
const rev=acquireSourceHistory('revision',1);releaseSourceHistory('revision',rev.handle,s);
assert.equal(acquireSourceHistory('revision',2).value,undefined);
const old=acquireSourceHistory('old',1);releaseSourceHistory('old',old.handle,s);
for(let i=0;i<16;i++){const h=acquireSourceHistory('note-'+i,1);releaseSourceHistory('note-'+i,h.handle,state('small'));}
assert.equal(acquireSourceHistory('old',1).value,undefined);
const huge=acquireSourceHistory('huge-edit',1);
const deletion=state(baseline).update({changes:{from:0,to:baseline.length}}).state;
releaseSourceHistory('huge-edit',huge.handle,deletion);
assert.equal(acquireSourceHistory('huge-edit',1).value,undefined,'oversized edit history is not retained across tabs');
assert.equal(command(undo,deletion).doc.toString(),baseline,'eviction leaves active history usable');
console.log('PASS: source history only retains edits, undo/redo, revision guard, stale-cleanup invalidation and tab count cap');
