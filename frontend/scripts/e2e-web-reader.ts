import assert from 'node:assert/strict';
import { chromium } from './browser-env.ts';
const base = process.env.INKISM_URL!;
const rpc = async (op: string, args: any = {}) => { const r = await fetch(base + '/api/rpc', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({op,...args})}); const v=await r.json(); assert.equal(v.ok,true,JSON.stringify(v)); return v.data; };
const original = await rpc('save',{note:{title:'Original preserved',content:'<p>untouched source</p>',content_format:'html'}});
await rpc('workspace_set',{ids:[original.id],active:original.id,locations:{}});
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']});
try {
 const page = await browser.newPage({viewport:{width:1100,height:900}});
 await page.addInitScript(()=>localStorage.setItem('inkism.lang','ko'));
 let reads=0,remote=0,saves=0;
 page.on('request',r=>{if(r.url().startsWith('https://reader.example'))remote++;if(r.url().endsWith('/api/rpc')&&r.postDataJSON()?.op==='save')saves++;});
 await page.route('**/api/reader',route=>{reads++;return route.fulfill({contentType:'application/json',body:JSON.stringify({ok:true,data:{url:'https://reader.example/article',title:'Reader fixture',html:'<h1>Reader fixture</h1><p>Static readable paragraph</p>',text:'Reader fixture\nStatic readable paragraph'}})});});
 await page.goto(base);
 await page.getByRole('button',{name:'웹 읽기',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'웹 읽기'});
 await dialog.getByLabel('웹페이지 주소').fill('https://reader.example/article');
 assert.equal(reads,0); assert.equal(remote,0);
 await dialog.getByRole('button',{name:'본문 읽기',exact:true}).click();
 await dialog.getByRole('heading',{name:'Reader fixture'}).waitFor();
 await page.frameLocator('iframe[title="읽기 본문"]').getByText('Static readable paragraph',{exact:true}).waitFor();
 assert.equal(await dialog.locator('iframe').getAttribute('sandbox'),'');
 await dialog.getByRole('button',{name:'텍스트로 보기'}).click();
 assert.match(await page.frameLocator('iframe[title="읽기 본문"]').locator('pre').innerText(),/Static readable paragraph/);
 assert.equal(await dialog.getByRole('link',{name:'원문 페이지 열기'}).getAttribute('rel'),'noopener noreferrer');
 await dialog.getByRole('button',{name:'새 노트로 저장'}).click();
 await dialog.getByRole('button',{name:'저장됨',exact:true}).waitFor();
 assert.equal(await dialog.getByRole('button',{name:'저장됨',exact:true}).isDisabled(),true);
 assert.equal((await rpc('get',{id:original.id})).content,original.content);
 assert.equal(reads,1);assert.equal(remote,0);assert(saves>=1);
 console.log('PASS explicit read only, isolated Reader/text mode, source-link, new-note save and original preserved');
} finally {await browser.close();}
